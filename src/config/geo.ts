/** Check if coordinates are within France or overseas territories */
export function isInFrance(lon: number, lat: number): boolean {
  // Metro
  if (
    lon >= FRANCE_BBOX.west &&
    lon <= FRANCE_BBOX.east &&
    lat >= FRANCE_BBOX.south &&
    lat <= FRANCE_BBOX.north
  ) {
    return true;
  }

  // DROM
  for (const bbox of DOM_TOM_BBOXES) {
    if (
      lon >= bbox.west &&
      lon <= bbox.east &&
      lat >= bbox.south &&
      lat <= bbox.north
    ) {
      return true;
    }
  }

  return false;
}
